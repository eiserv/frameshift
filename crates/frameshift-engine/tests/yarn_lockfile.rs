fn classic(text: &str) -> Result<Lockfile, LockfileError> {
    let source = SourceText::new(text.into(), TextLimits::default()).unwrap();
    Lockfile::from_yarn_classic(&parse_yarn_lockfile(&source, YarnLimits::default()).unwrap())
}

fn berry(text: &str) -> Result<Lockfile, LockfileError> {
    let source = SourceText::new(text.into(), TextLimits::default()).unwrap();
    Lockfile::from_yarn_berry(&parse_yaml(&source, YamlLimits::default()).unwrap())
}

fn manifest(text: &str) -> PackageManifest {
    let source = SourceText::new(text.into(), TextLimits::default()).unwrap();
    let document = parse_json(&source, JsonDialect::Json, JsonLimits::default()).unwrap();
    PackageManifest::from_json(&document).unwrap()
}

fn version(package: Option<&LockedPackage>) -> Option<String> {
    package
        .and_then(LockedPackage::version)
        .map(ToString::to_string)
}

#[test]
fn classic_entries_resolve_by_pattern() {
    let lockfile = classic(CLASSIC).unwrap();
    assert_eq!(lockfile.kind(), LockfileKind::Yarn);
    assert_eq!(lockfile.version(), 1);
    assert!(lockfile.workspaces().is_empty());
    assert_eq!(lockfile.packages().len(), 6);
    // Yarn 1 records no workspaces, so declarations need their ranges.
    assert_eq!(lockfile.resolve("", "fictional-tagged"), None);
    let tagged = lockfile.resolve_declared("", "fictional-tagged", "latest");
    assert_eq!(version(tagged), Some("3.0.0".into()));
    assert_eq!(
        lockfile.resolve_declared("", "fictional-tagged", "^3.0.0"),
        None
    );
    let alias = lockfile
        .resolve_declared("", "fictional-alias", "npm:fictional-leaf@^2.0.0")
        .unwrap();
    assert_eq!(&*alias.name, "fictional-leaf");
    assert_eq!(&*alias.key, "fictional-alias@npm:fictional-leaf@^2.0.0");
    assert_eq!(version(Some(alias)), Some("2.0.1".into()));
    let scoped = lockfile
        .resolve_declared("", "@fictional/scoped", "^2.0.0")
        .unwrap();
    assert_eq!(
        version(lockfile.resolve_from(scoped, "fictional-leaf")),
        Some("1.4.0".into())
    );
    assert_eq!(
        version(lockfile.resolve_from(tagged.unwrap(), "fictional-leaf")),
        Some("1.4.0".into())
    );
    // Local sources keep their text and are not registry versions.
    let local = lockfile
        .resolve_declared("", "fictional-local", "file:./local/thing")
        .unwrap();
    assert_eq!(
        local.resolution,
        Resolution::Other("file:./local/thing".into())
    );
    let linked = lockfile
        .resolve_declared("", "fictional-linked", "link:./local/linked")
        .unwrap();
    assert_eq!(linked.version(), None);
}

#[test]
fn classic_staleness_is_a_missing_pattern() {
    let lockfile = classic(CLASSIC).unwrap();
    let current = manifest(
        r#"{"dependencies": {"fictional-tagged": "latest", "@fictional/scoped": "^2.0.0"},
            "devDependencies": {"fictional-leaf": "^1.0.0"},
            "peerDependencies": {"fictional-absent": "^9"}}"#,
    );
    assert!(lockfile.out_of_sync(&current).is_empty());
    let changed = manifest(
        r#"{"dependencies": {"fictional-tagged": "^3"},
            "optionalDependencies": {"fictional-leaf": "^1.0.0"}}"#,
    );
    assert_eq!(lockfile.out_of_sync(&changed), [DependencyKind::Production]);
}

#[test]
fn classic_structure_is_checked_as_a_whole() {
    let rejected = |text: &str| classic(text).unwrap_err().kind;
    let structure = LockfileErrorKind::Structure;
    // A dependency without its own entry.
    assert_eq!(
        rejected("a@^1:\n  version \"1.0.0\"\n  dependencies:\n    b \"^1\"\n"),
        structure
    );
    // Duplicate patterns, also across entries.
    assert_eq!(
        rejected("a@^1:\n  version \"1.0.0\"\na@^1:\n  version \"1.0.1\"\n"),
        structure
    );
    // Patterns of different packages in one entry.
    assert_eq!(rejected("a@^1, b@^1:\n  version \"1.0.0\"\n"), structure);
    // An alias and a plain pattern in one entry.
    assert_eq!(
        rejected("a@^1, \"a@npm:b@^1\":\n  version \"1.0.0\"\n"),
        structure
    );
    // Values of other types, and entries that are not objects.
    assert_eq!(rejected("a@^1:\n  version 1\n"), structure);
    assert_eq!(
        rejected("a@^1:\n  resolved:\n    x y\n  version \"1.0.0\"\n"),
        structure
    );
    assert_eq!(rejected("a@^1 \"a@^1.0.0\"\n"), structure);
    assert_eq!(
        rejected("a@^1:\n  resolved \"https://x.example/a.tgz\"\n"),
        structure
    );
    assert_eq!(rejected("\"a b@^1\":\n  version \"1.0.0\"\n"), structure);
    // Other sources than the registry keep their text.
    let git = classic(
        "\"a@github:fictional/a#v1\":\n  version \"1.0.0\"\n  resolved \"https://codeload.example/a/tar.gz/0\"\n",
    )
    .unwrap();
    assert_eq!(git.packages()[0].version(), None);
    let mirror =
        classic("a@^1:\n  version \"1.0.0\"\n  resolved \"git+ssh://x.example/a.git\"\n").unwrap();
    assert_eq!(
        mirror.packages()[0].resolution,
        Resolution::Other("git+ssh://x.example/a.git".into())
    );
    // A bare pattern, as `yarn add` once wrote it, is found first.
    let bare = classic("a:\n  version \"1.0.0\"\na@^1:\n  version \"1.1.0\"\n").unwrap();
    assert_eq!(
        version(bare.resolve_declared("", "a", "^1")),
        Some("1.0.0".into())
    );
}

