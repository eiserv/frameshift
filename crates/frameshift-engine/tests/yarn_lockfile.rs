//! Yarn classic and Berry lockfile contracts through the engine facade,
//! and an opt-in check against installs of reference projects (`D-072`).
//!
//! The hand-written lockfiles mirror the structure that Yarn 1.22.22,
//! 2.4.3, 3.8.7, and 4.18.1 write, with fictional package names.

mod support;

use std::path::Path;

use frameshift_engine::foundation::{
    FindingCollector, FindingLimits, SourcePath, SourceText, TextLimits,
};
use frameshift_engine::input::snapshot;
use frameshift_engine::limits::Limits;
use frameshift_engine::package::{
    DependencyKind, DependencySpec, LockedPackage, Lockfile, LockfileError, LockfileErrorKind,
    LockfileKind, LockfileState, ManifestState, PackageManifest, Resolution, load_package,
};
use frameshift_engine::syntax::{
    JsonDialect, JsonLimits, YamlLimits, YarnLimits, parse_json, parse_yaml, parse_yarn_lockfile,
};
use support::Json;

