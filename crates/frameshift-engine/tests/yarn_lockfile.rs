#[test]
fn berry_descriptors_resolve_with_workspaces_aliases_and_bound_paths() {
    let lockfile = berry(BERRY).unwrap();
    assert_eq!(lockfile.kind(), LockfileKind::Yarn);
    assert_eq!(lockfile.version(), 10);
    let paths: Vec<&str> = lockfile.workspaces().iter().map(|ws| &*ws.path).collect();
    assert_eq!(paths, ["", "packages/side"]);
    let root = lockfile.workspace("").unwrap();
    assert_eq!(root.name.as_deref(), Some("fictional-root"));
    // Yarn records a marker instead of the workspace's version.
    assert_eq!(root.version, None);
    assert_eq!(root.declared(DependencyKind::Production).len(), 4);
    assert_eq!(
        lockfile.resolve("", "@fictional/side").unwrap().resolution,
        Resolution::Workspace("packages/side".into())
    );
    let alias = lockfile.resolve("", "fictional-alias").unwrap();
    assert_eq!(
        (&*alias.name, &*alias.key),
        ("fictional-leaf", "fictional-leaf@npm:2.0.1")
    );
    let leaf = lockfile.resolve("", "fictional-leaf").unwrap();
    assert_eq!(version(Some(leaf)), Some("1.4.0".into()));
    assert_eq!(&*leaf.optional_peers, [Box::from("fictional-peer")]);
    assert_eq!(
        version(lockfile.resolve_from(leaf, "fictional-tiny")),
        Some("1.0.2".into())
    );
    // A local path is bound to the workspace that declares it.
    let local = lockfile.resolve("", "fictional-local").unwrap();
    assert!(
        matches!(&local.resolution, Resolution::Other(text) if text.starts_with("fictional-local@file:"))
    );
    // Declarations are looked up by their normalized range.
    assert_eq!(
        version(lockfile.resolve_declared("", "fictional-leaf", "^1.0.0")),
        Some("1.4.0".into())
    );
    assert_eq!(
        lockfile.resolve_declared("", "fictional-leaf", "^1.5.0"),
        None
    );
    assert_eq!(
        version(lockfile.resolve("packages/side", "fictional-leaf")),
        Some("1.4.0".into())
    );
    assert!(
        lockfile
            .resolve_declared("", "fictional-local", "./local/thing")
            .is_some()
    );
    // Peer ranges are recorded but not installed by the workspace.
    let side = lockfile.workspace("packages/side").unwrap();
    assert_eq!(side.declared(DependencyKind::Peer).len(), 1);
    assert_eq!(lockfile.resolve("packages/side", "fictional-peer"), None);
}

#[test]
fn berry_formats_up_to_6_omit_the_npm_protocol() {
    let legacy = BERRY
        .replace("version: 10\n", "version: 6\n")
        .replace("\"npm:^1.0.0\"", "^1.0.0")
        .replace("\"npm:1\"", "1")
        .replace("\"fictional-leaf@npm:^1.0.0\":", "fictional-leaf@^1.0.0:")
        .replace("\"fictional-tiny@npm:1\":", "fictional-tiny@1:");
    let lockfile = berry(&legacy).unwrap();
    assert_eq!(lockfile.version(), 6);
    let leaf = lockfile.resolve("", "fictional-leaf").unwrap();
    assert_eq!(version(Some(leaf)), Some("1.4.0".into()));
    assert_eq!(
        version(lockfile.resolve_from(leaf, "fictional-tiny")),
        Some("1.0.2".into())
    );
    // Version 10 keys are read as written, so this one is not found.
    let current = berry(&BERRY.replace("\"fictional-tiny@npm:1\":", "fictional-tiny@1:")).unwrap();
    let leaf = current.resolve("", "fictional-leaf").unwrap();
    assert_eq!(current.resolve_from(leaf, "fictional-tiny"), None);
}

#[test]
fn berry_staleness_compares_effective_declarations() {
    let lockfile = berry(BERRY).unwrap();
    let current = manifest(
        r#"{"dependencies": {"@fictional/side": "workspace:*", "fictional-local": "file:./local/thing",
              "fictional-leaf": "^0.1"},
            "devDependencies": {"fictional-alias": "npm:fictional-leaf@^2.0.0"},
            "optionalDependencies": {"fictional-leaf": "^1.0.0"}}"#,
    );
    // Optional overrides production; ranges are compared normalized.
    assert!(lockfile.out_of_sync(&current).is_empty());
    let changed = manifest(
        r#"{"dependencies": {"@fictional/side": "workspace:*", "fictional-local": "file:./local/thing"},
            "devDependencies": {"fictional-alias": "npm:fictional-leaf@^2.1.0"},
            "peerDependencies": {"fictional-peer": "^2"}}"#,
    );
    assert_eq!(
        lockfile.out_of_sync(&changed),
        [
            DependencyKind::Production,
            DependencyKind::Development,
            DependencyKind::Peer
        ]
    );
}

#[test]
fn berry_versions_and_structure_fail_closed() {
    let kind = |text: &str| berry(text).unwrap_err().kind;
    let unsupported = LockfileErrorKind::UnsupportedVersion;
    let structure = LockfileErrorKind::Structure;
    for version in ["7", "3", "11", "06", "x"] {
        assert_eq!(
            kind(&BERRY.replace("version: 10\n", &format!("version: {version}\n"))),
            unsupported,
            "{version}"
        );
    }
    for version in ["4", "5", "8", "9", "\"10\""] {
        let text = BERRY.replace("version: 10\n", &format!("version: {version}\n"));
        assert!(berry(&text).is_ok(), "{version}");
    }
    // A YAML lockfile without metadata is not a Berry lockfile, nor is one
    // of comments only, which Yarn reads as an empty object.
    assert_eq!(
        kind("\"a@npm:1\":\n  resolution: \"a@npm:1.0.0\"\n  linkType: hard\n"),
        unsupported
    );
    assert_eq!(kind("# only a comment\n"), unsupported);
    assert_eq!(kind(""), unsupported);
    // A scalar or sequence at the top is no object at all.
    assert_eq!(kind("text\n"), structure);
    assert_eq!(kind("- a\n"), structure);
    // Scalars are strings, as under Yarn's failsafe schema.
    let plain = "__metadata:\n  version: 10\n\"a@npm:1\":\n  version: 1.0.0\n  resolution: \"a@npm:1.0.0\"\n  dependencies:\n    b: true\n  linkType: hard\n\"b@npm:true\":\n  resolution: \"b@npm:1.0.0\"\n  linkType: hard\n";
    let lockfile = berry(plain).unwrap();
    assert_eq!(
        version(
            lockfile
                .package("a@npm:1.0.0")
                .and_then(|a| lockfile.resolve_from(a, "b"))
        ),
        Some("1.0.0".into())
    );
    // A dependency without an entry, as after `resolutions`, is unresolved.
    let missing =
        berry(&BERRY.replace("fictional-tiny: \"npm:1\"", "fictional-tiny: \"npm:2\"")).unwrap();
    let leaf = missing.resolve("", "fictional-leaf").unwrap();
    assert_eq!(missing.resolve_from(leaf, "fictional-tiny"), None);
    for (from, to) in [
        // A resolution without a version for the registry entry.
        (
            "resolution: \"fictional-tiny@npm:1.0.2\"",
            "resolution: \"fictional-tiny\"",
        ),
        // A recorded version that differs from the resolution.
        ("version: 1.0.2\n", "version: 1.0.3\n"),
        // An unknown link type.
        ("linkType: hard\n", "linkType: copy\n"),
        // A flag that Yarn cannot read.
        ("optional: true", "optional: maybe"),
        // A tag that the failsafe schema does not have.
        ("version: 1.0.2\n", "version: !!int 1\n"),
        // A null value.
        ("checksum: 10c0/03", "checksum:"),
    ] {
        assert!(BERRY.contains(from), "{from}");
        assert_eq!(kind(&BERRY.replacen(from, to, 1)), structure, "{to}");
    }
    // The same descriptor in two entries is ambiguous.
    let duplicate = BERRY.replace(
        "\"fictional-tiny@npm:1\":",
        "\"fictional-tiny@npm:1, fictional-leaf@npm:^1.0.0\":",
    );
    assert_eq!(kind(&duplicate), structure);
    // Two documents.
    assert_eq!(kind(&format!("{BERRY}---\n{BERRY}")), structure);
}

/// Reads `oracle.json` cases of a reference project directory written by
/// the external script, and checks that each declaration resolves to the
/// package that the install placed where Node.js finds it.
fn check_reference_project(root: &Path) -> (u64, usize, usize) {
    let mut findings = FindingCollector::new(FindingLimits::default());
    let limits = Limits::default();
    let snapshot = snapshot(root, limits.snapshot(), &mut findings).unwrap();
    let loaded = load_package(&snapshot, None, limits.package(), &mut findings).unwrap();
    assert!(matches!(loaded.manifest, ManifestState::Analyzed(_)));
    let LockfileState::Parsed(lockfile) = &loaded.lockfile else {
        panic!(
            "{}: lockfile not parsed: {:?}",
            root.display(),
            findings.finish()
        );
    };
    let text = std::fs::read_to_string(root.join("oracle.json")).unwrap();
    let oracle = support::parse(&text).unwrap();
    let Some(Json::Array(cases)) = oracle.get("cases") else {
        panic!("oracle.json has no cases");
    };
    for case in cases {
        let field = |name: &str| case.get(name).and_then(Json::as_str).unwrap();
        let (workspace, name, spec) = (field("workspace"), field("name"), field("spec"));
        let installed = case.get("installed").unwrap();
        let resolved = lockfile.resolve_declared(workspace, name, spec);
        let context = format!("{}: {workspace} {name} {spec}", root.display());
        let local = installed.get("local") == Some(&Json::Bool(true));
        match resolved.map(|package| &package.resolution) {
            Some(Resolution::Registry(version)) => {
                assert_eq!(
                    installed.get("name").and_then(Json::as_str),
                    Some(&*resolved.unwrap().name),
                    "{context}"
                );
                assert_eq!(
                    installed.get("version").and_then(Json::as_str),
                    Some(version.to_string().as_str()),
                    "{context}"
                );
                assert!(!local, "{context}");
            }
            Some(Resolution::Workspace(_)) => assert!(local, "{context}"),
            Some(Resolution::Other(_) | Resolution::Link(_)) => assert!(
                !matches!(
                    DependencySpec::parse(spec),
                    DependencySpec::Range(_)
                        | DependencySpec::Tag(_)
                        | DependencySpec::Alias { .. }
                ),
                "{context}"
            ),
            // Yarn 1 records no entry for a workspace package.
            None => assert!(lockfile.version() == 1 && local, "{context}"),
        }
    }
    // Every dependency of a locked package resolves, except protocols that
    // the model leaves unresolved.
    let mut unresolved = 0;
    for package in lockfile.packages() {
        for dependency in &package.dependencies {
            if lockfile.resolve_from(package, &dependency.name).is_none() {
                unresolved += 1;
            }
        }
    }
    let findings = findings.finish();
    for (_, finding) in findings.iter() {
        println!("  {} {}", finding.code().as_str(), finding.message());
    }
    let _ = SourcePath::new("package.json", Default::default());
    (lockfile.version(), lockfile.packages().len(), unresolved)
}

#[test]
#[ignore = "external reference: set FRAMESHIFT_YARN_PROJECTS to installed reference project directories"]
fn external_reference_projects() {
    let paths = std::env::var_os("FRAMESHIFT_YARN_PROJECTS")
        .expect("FRAMESHIFT_YARN_PROJECTS names installed reference projects");
    for path in std::env::split_paths(&paths) {
        let (version, packages, unresolved) = check_reference_project(&path);
        println!(
            "{}: format {version}, {packages} packages, {unresolved} unresolved transitive dependencies",
            path.display()
        );
    }
}

/// Compares every dependency of every entry of the lockfiles named by
/// `FRAMESHIFT_YARN_LOCKFILES` with JSON lines in `<lockfile>.oracle`,
/// which a script outside the repository derives with Yarn's own parsers:
/// `[parent key, dependency name, expected key or null]`.
#[test]
#[ignore = "external reference: set FRAMESHIFT_YARN_LOCKFILES to lockfiles with oracle files"]
fn external_reference_lockfiles() {
    let paths = std::env::var_os("FRAMESHIFT_YARN_LOCKFILES")
        .expect("FRAMESHIFT_YARN_LOCKFILES names lockfiles with .oracle files");
    for path in std::env::split_paths(&paths) {
        let text = std::fs::read_to_string(&path).unwrap();
        let classic_header = text
            .lines()
            .take_while(|line| line.starts_with('#'))
            .any(|line| line.trim_end() == "# yarn lockfile v1");
        let lockfile = if classic_header {
            classic(&text).unwrap()
        } else {
            berry(&text).unwrap()
        };
        let mut oracle = path.clone().into_os_string();
        oracle.push(".oracle");
        let lines = std::fs::read_to_string(oracle).unwrap();
        let (mut resolved, mut unresolved) = (0, 0);
        for line in lines.lines() {
            let Json::Array(items) = support::parse(line).unwrap() else {
                panic!("{line}");
            };
            let [Json::String(parent), Json::String(name), expected] = items.as_slice() else {
                panic!("{line}");
            };
            let package = lockfile
                .package(parent)
                .unwrap_or_else(|| panic!("{}: no entry {parent}", path.display()));
            let actual = lockfile
                .resolve_from(package, name)
                .map(|found| &*found.key);
            assert_eq!(
                actual,
                expected.as_str(),
                "{}: {parent} -> {name}",
                path.display()
            );
            if actual.is_some() {
                resolved += 1;
            } else {
                unresolved += 1;
            }
        }
        println!(
            "{}: format {}, {} workspaces, {} packages, {resolved} dependencies resolved, \
             {unresolved} unresolved as by the oracle",
            path.display(),
            lockfile.version(),
            lockfile.workspaces().len(),
            lockfile.packages().len()
        );
    }
}
