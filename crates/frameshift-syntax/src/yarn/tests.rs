//! Yarn classic lockfile grammar, quirk, error, duplicate-key, and limit
//! contracts.

use frameshift_core::TextLimits;

use super::*;

fn text(source: &str) -> SourceText {
    SourceText::new(source.to_owned(), TextLimits::default()).unwrap()
}

/// Replaces `|BS|` with a backslash, so escape sequences in test input are
/// spelled without one.
fn esc(source: &str) -> String {
    source.replace("|BS|", "\\")
}

fn parse(source: &SourceText) -> Result<YarnDocument<'_>, YarnError> {
    parse_yarn_lockfile(source, YarnLimits::default())
}

fn error(source: &str) -> (YarnErrorKind, usize, usize) {
    let source = text(source);
    let error = parse(&source).unwrap_err();
    (error.kind(), error.span().start(), error.span().end())
}

/// Renders a value as JSON-like text: objects list each member's keys,
/// joined with `,`, then the value.
fn render(document: &YarnDocument<'_>, id: YarnId) -> String {
    match document.value(id).unwrap() {
        YarnValue::String(value) => format!("{value:?}"),
        YarnValue::Number(digits) => format!("#{digits}"),
        YarnValue::Bool(value) => value.to_string(),
        YarnValue::Object(object) => {
            let members: Vec<String> = object
                .members()
                .map(|member| {
                    let keys: Vec<String> = member
                        .keys()
                        .map(|key| format!("{:?}", key.text()))
                        .collect();
                    format!("{}:{}", keys.join(","), render(document, member.value()))
                })
                .collect();
            format!("{{{}}}", members.join(","))
        }
    }
}

fn rendered(source: &str) -> String {
    let source = text(source);
    let document = parse(&source).unwrap();
    render(&document, document.root())
}

const LOCKFILE: &str = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


\"@scope/thing@^1.0.0\", \"@scope/thing@^1.2.0\":
  version \"1.2.3\"
  resolved \"https://registry.example/@scope/thing/-/thing-1.2.3.tgz#0123\"
  integrity sha512-abc/def+ghi==
  dependencies:
    wrap-it \"1\"
    \"other-thing\" \"^2.0.0 || ^3.0.0\"

wrap-it@1:
  version \"1.0.2\"
";

#[test]
fn reads_the_format_that_yarn_writes() {
    assert_eq!(
        rendered(LOCKFILE),
        concat!(
            "{\"@scope/thing@^1.0.0\",\"@scope/thing@^1.2.0\":{",
            "\"version\":\"1.2.3\",",
            "\"resolved\":\"https://registry.example/@scope/thing/-/thing-1.2.3.tgz#0123\",",
            "\"integrity\":\"sha512-abc/def+ghi==\",",
            "\"dependencies\":{\"wrap-it\":\"1\",\"other-thing\":\"^2.0.0 || ^3.0.0\"}},",
            "\"wrap-it@1\":{\"version\":\"1.0.2\"}}"
        )
    );
    let source = text(LOCKFILE);
    let document = parse(&source).unwrap();
    assert!(!document.has_bom());
    let root = document
        .value(document.root())
        .unwrap()
        .as_object()
        .unwrap();
    assert_eq!(root.len(), 2);
    let first = root.member(0).unwrap();
    assert_eq!(first.key_count(), 2);
    let keys: Vec<Span> = first.keys().map(YarnKey::span).collect();
    let start = LOCKFILE.find("\"@scope").unwrap();
    assert_eq!(keys[0], Span::new(start, start + 21).unwrap());
    assert_eq!(first.span().start(), start);
    let entry = document.value(first.value()).unwrap().as_object().unwrap();
    assert_eq!(
        document.span(first.value()).unwrap().start(),
        LOCKFILE.find("version").unwrap()
    );
    assert_eq!(
        first.span().end(),
        document.span(first.value()).unwrap().end()
    );
    let version = entry.get("version").unwrap();
    assert_eq!(document.value(version).unwrap().as_str(), Some("1.2.3"));
    let at = LOCKFILE.find("\"1.2.3\"").unwrap();
    assert_eq!(
        document.span(version).unwrap(),
        Span::new(at, at + 7).unwrap()
    );
    assert!(entry.get("missing").is_none());
    assert_eq!(document.duplicate_keys().len(), 0);
    // Identities ascend in source order, and the root comes first.
    assert_eq!(document.root().index(), 0);
    assert!(first.value() < version);
}

#[test]
fn crlf_bom_and_empty_input() {
    let source = text("\u{FEFF}# yarn lockfile v1\r\n\r\na@^1:\r\n  version \"1.0.0\"\r\n");
    let document = parse(&source).unwrap();
    assert!(document.has_bom());
    assert_eq!(
        render(&document, document.root()),
        "{\"a@^1\":{\"version\":\"1.0.0\"}}"
    );
    let member = document
        .value(document.root())
        .unwrap()
        .as_object()
        .unwrap()
        .member(0)
        .unwrap();
    assert_eq!(member.keys().next().unwrap().span().start(), 25);
    assert_eq!(rendered(""), "{}");
    assert_eq!(rendered("# only a comment\n\n"), "{}");
    assert_eq!(rendered("\u{FEFF}"), "{}");
}

#[test]
fn reproduces_the_quirks_of_yarns_tokenizer() {
    // Digit runs are numbers, `true` and `false` prefixes are booleans, and
    // the rest of a word becomes the next key.
    assert_eq!(
        rendered("a 12\nb true\nc false\n"),
        "{\"a\":#12,\"b\":true,\"c\":false}"
    );
    assert_eq!(rendered("a trueb false\n"), "{\"a\":true,\"b\":false}");
    // A colon before a scalar is optional, and several pairs may share a line.
    assert_eq!(rendered("a: \"x\" b y\n"), "{\"a\":\"x\",\"b\":\"y\"}");
    // Unquoted words run to a colon, space, comma, or line end, and may hold
    // characters that quoted keys need elsewhere.
    assert_eq!(rendered("w@1#x\"y z\n"), "{\"w@1#x\\\"y\":\"z\"}");
    // A blank line of two LFs is one newline, and leading spaces at the
    // start of the file are not indentation.
    assert_eq!(rendered("  a:\n\n  b c\n"), "{\"a\":{\"b\":\"c\"}}");
    // Spaces after a lone CR are not indentation, so they do not nest.
    assert_eq!(
        rendered("a:\r  b c\nd e\n"),
        "{\"a\":{},\"b\":\"c\",\"d\":\"e\"}"
    );
    // Comments may follow a value and need no space before them.
    assert_eq!(
        rendered("a b # note\nc d#e\n"),
        "{\"a\":\"b\",\"c\":\"d#e\"}"
    );
    // A key with a colon and nothing after it is an empty object.
    assert_eq!(rendered("a:\nb:"), "{\"a\":{},\"b\":{}}");
    // Nested objects end at a smaller indentation, also several at once.
    assert_eq!(
        rendered("a:\n  b:\n    c d\ne:\n  f g\n"),
        "{\"a\":{\"b\":{\"c\":\"d\"}},\"e\":{\"f\":\"g\"}}"
    );
    assert_eq!(
        rendered("a:\n  b:\n    c d\n  e f\n"),
        "{\"a\":{\"b\":{\"c\":\"d\"},\"e\":\"f\"}}"
    );
    // Lines of spaces inside an object are blank lines of that object.
    assert_eq!(
        rendered("a:\n  b c\n  \n  d e\n"),
        "{\"a\":{\"b\":\"c\",\"d\":\"e\"}}"
    );
}

#[test]
fn decodes_quoted_strings_as_json_parse() {
    let source = esc("a \"x|BS|n|BS|u00e9|BS|ud83d|BS|ude00|BS|\"|BS||BS||BS|/\"\n");
    assert_eq!(
        rendered(&source),
        "{\"a\":\"x\\n\u{e9}\u{1f600}\\\"\\\\/\"}"
    );
    assert_eq!(rendered("a \"\"\n"), "{\"a\":\"\"}");
    // The string ends at a quote after two backslashes, as in JSON.
    assert_eq!(rendered(&esc("a \"x|BS||BS|\"\n")), "{\"a\":\"x\\\\\"}");
    // After three backslashes, Yarn ends the token early, so `JSON.parse`
    // fails on it.
    assert_eq!(
        error(&esc("a \"x|BS||BS||BS|\"y\"\n")).0,
        YarnErrorKind::InvalidToken
    );
    for invalid in [
        "a \"x\ty\"\n",
        "a \"x\n",
        "a \"x|BS|q\"\n",
        "a \"x|BS|u12\"\n",
        "a \"|BS|ud800\"\n",
        "a \"|BS|ud800|BS|u0041\"\n",
        "a \"|BS|udc00\"\n",
    ] {
        assert_eq!(
            error(&esc(invalid)).0,
            YarnErrorKind::InvalidToken,
            "{invalid:?}"
        );
    }
}

#[test]
fn rejects_what_yarn_rejects_or_reads_differently() {
    assert_eq!(error("a:\n   b c\n"), (YarnErrorKind::Indentation, 3, 6));
    // Yarn ignores everything after indentation at the top level.
    assert_eq!(error("a b\n  c d\n").0, YarnErrorKind::Indentation);
    // One blank line inside an object is part of a single newline token,
    // two are not, and neither is a blank CRLF line.
    assert_eq!(
        rendered("a:\n  b c\n\n  d e\n"),
        "{\"a\":{\"b\":\"c\",\"d\":\"e\"}}"
    );
    assert_eq!(
        error("a:\n  b c\n\n\n  d e\n").0,
        YarnErrorKind::Indentation
    );
    assert_eq!(
        error("a:\r\n  b c\r\n\r\n  d e\r\n").0,
        YarnErrorKind::Indentation
    );
    assert_eq!(error("a:\n    b c\n").0, YarnErrorKind::Indentation);
    // A tab starts no token, but a word may contain one.
    assert_eq!(error("a \tb\n"), (YarnErrorKind::InvalidToken, 2, 3));
    assert_eq!(rendered("a\tb c\n"), "{\"a\\tb\":\"c\"}");
    assert_eq!(error("@a b\n"), (YarnErrorKind::InvalidToken, 0, 1));
    assert_eq!(error("a b, c\n"), (YarnErrorKind::UnexpectedToken, 3, 4));
    assert_eq!(error("a, 1 b\n"), (YarnErrorKind::UnexpectedToken, 3, 4));
    assert_eq!(error("a\n"), (YarnErrorKind::UnexpectedToken, 1, 2));
    assert_eq!(error(": b\n"), (YarnErrorKind::UnexpectedToken, 0, 1));
    assert_eq!(error("1 b\n"), (YarnErrorKind::UnexpectedToken, 0, 1));
    assert_eq!(error("true b\n"), (YarnErrorKind::UnexpectedToken, 0, 4));
    assert_eq!(error("a: :\n").0, YarnErrorKind::UnexpectedToken);
    assert_eq!(error("\"\" b\n"), (YarnErrorKind::EmptyKey, 0, 2));
    assert_eq!(error("a, \"\" b\n"), (YarnErrorKind::EmptyKey, 3, 5));
    assert_eq!(error("a:\n  \"\" b\n").0, YarnErrorKind::EmptyKey);
}

#[test]
fn rejects_merge_conflicts_and_newer_versions() {
    let conflict = "<<<<<<< HEAD\na b\n=======\na c\n>>>>>>> branch\n";
    assert_eq!(error(conflict), (YarnErrorKind::MergeConflict, 0, 7));
    // All three markers must occur, anywhere, as in Yarn.
    assert_eq!(
        error("a \"<<<<<<< ======= >>>>>>>\"\n").0,
        YarnErrorKind::MergeConflict
    );
    assert_eq!(
        rendered("a \"<<<<<<< =======\"\n"),
        "{\"a\":\"<<<<<<< =======\"}"
    );
    for newer in [
        "# yarn lockfile v2\n",
        "#yarn lockfile v10\n",
        "# yarn lockfile v002 \r\n",
        "a b # yarn lockfile v3\n",
        "#\u{FEFF}yarn lockfile v2\u{3000}\n",
    ] {
        assert_eq!(
            error(newer).0,
            YarnErrorKind::UnsupportedVersion,
            "{newer:?}"
        );
    }
    for accepted in [
        "# yarn lockfile v1\n",
        "# yarn lockfile v01\n",
        "# yarn lockfile v0\n",
        "# yarn lockfile v2x\n",
        "# Yarn lockfile v2\n",
        "# yarn lockfile v\n",
        "# yarn lockfile v2\u{85}\n",
    ] {
        assert_eq!(rendered(accepted), "{}", "{accepted:?}");
    }
}

#[test]
fn reports_duplicate_keys_and_returns_the_last() {
    let source = text("a 1\nb, a 2\nc:\n  d e\n  d f\nb 3\n");
    let document = parse(&source).unwrap();
    let duplicates: Vec<(&str, usize)> = document
        .duplicate_keys()
        .map(|key| (key.text(), key.span().start()))
        .collect();
    assert_eq!(duplicates, [("a", 0), ("b", 4), ("d", 16)]);
    let root = document
        .value(document.root())
        .unwrap()
        .as_object()
        .unwrap();
    let value = |id| render(&document, id);
    assert_eq!(value(root.get("a").unwrap()), "#2");
    assert_eq!(value(root.get("b").unwrap()), "#3");
    let c = document
        .value(root.get("c").unwrap())
        .unwrap()
        .as_object()
        .unwrap();
    assert_eq!(value(c.get("d").unwrap()), "\"f\"");
    assert!(root.member(1).unwrap().keys().next().unwrap().is_shadowed());
    // One member that repeats a key is a duplicate as well.
    let source = text("a, a b\n");
    assert_eq!(parse(&source).unwrap().duplicate_keys().len(), 1);
}

#[test]
fn enforces_depth_and_node_limits() {
    let deep = "a:\n  b:\n    c:\n      d e\n";
    let limits = |max_depth, max_nodes| YarnLimits {
        max_depth,
        max_nodes,
    };
    let source = text(deep);
    assert!(parse_yarn_lockfile(&source, limits(4, 100)).is_ok());
    let error = parse_yarn_lockfile(&source, limits(3, 100)).unwrap_err();
    assert_eq!(error.kind(), YarnErrorKind::DepthLimit { limit: 3 });
    assert_eq!(error.span().start(), deep.find("\n      d").unwrap());
    let error = parse_yarn_lockfile(&source, limits(0, 100)).unwrap_err();
    assert_eq!(error.kind(), YarnErrorKind::DepthLimit { limit: 0 });
    // Four objects, four keys, and one string.
    assert!(parse_yarn_lockfile(&source, limits(4, 9)).is_ok());
    let error = parse_yarn_lockfile(&source, limits(4, 8)).unwrap_err();
    assert_eq!(error.kind(), YarnErrorKind::NodeLimit { limit: 8 });
    assert_eq!(parse(&source).unwrap().node_count(), 9);
    let displayed = error.to_string();
    assert!(displayed.contains("yarn.max-nodes"), "{displayed}");
}

#[test]
fn errors_never_echo_source_text() {
    for source in [
        "secret-key\n",
        "a:\n   secret-value\n",
        "a \"secret\tvalue\"\n",
        "# yarn lockfile v9 secret\n# yarn lockfile v9\n",
    ] {
        let message = parse(&text(source)).unwrap_err().to_string();
        assert!(!message.contains("secret"), "{message}");
    }
}
